#include "stm32f10x.h"

#include "sys.h"
#include "motor.h"
#include "usart.h"
#include "delay.h"
#include "colorful_led.h"


// =============================================
// UART ????
// =============================================

extern u8 CAR_buff[4];

extern u8 uart_rec_flag;


// =============================================
// Hi3861?????PWM
//
// Hi3861:0 ~ 150
// STM32 PWM:0 ~ 7199
// =============================================

static int Speed_To_PWM(u8 speed)
{
    int pwm;


    if (speed == 0)
    {
        return 0;
    }


    // ????
    pwm = speed * 40;


    // =========================================
    // ????????? PWM
    //
    // 20 × 40 = 800
    // ?????,????? 1200
    // =========================================

    if (pwm < 1200)
    {
        pwm = 1200;
    }


    // ????? 6000
    if (pwm > 6000)
    {
        pwm = 6000;
    }


    return pwm;
}


int main(void)
{
    int pwm_A;
    int pwm_B;


    // =========================================
    // ?????
    // =========================================

    delay_init();

    Stm32_Clock_Init(9);

    MY_NVIC_PriorityGroupConfig(2);


    // =========================================
    // UART
    // =========================================

    uart_init(115200);


    // =========================================
    // SWD
    // =========================================

    JTAG_Set(JTAG_SWD_DISABLE);

    JTAG_Set(SWD_ENABLE);


    // =========================================
    // ?? PWM
    // =========================================

    PWM_Init(7199, 9);


    // =========================================
    // WS2812
    // =========================================

    colorful_led_Init();


    // =========================================
    // ????
    // =========================================

    Set_Pwm(0, 0);

    Turn_Off_LED();


    // =========================================
    // ??? SysTick PID
    //
    // ??????:
    //
    // SysTick_Config(...)
    //
    // ??????
    // =========================================


    while (1)
    {
        if (uart_rec_flag == 1)
        {
            // =================================
            // A ??
            // =================================

            pwm_A =
                Speed_To_PWM(
                    CAR_buff[1]
                );


            if (CAR_buff[0] == 1)
            {
                pwm_A = -pwm_A;
            }


            // =================================
            // B ??
            // =================================

            pwm_B =
                Speed_To_PWM(
                    CAR_buff[3]
                );


            if (CAR_buff[2] == 1)
            {
                pwm_B = -pwm_B;
            }


            // =================================
            // ?????
            // =================================

            Set_Pwm(
                pwm_A,
                pwm_B
            );


            // =================================
            // ??
            // =================================

            if (
                CAR_buff[1] == 0
                &&
                CAR_buff[3] == 0
            )
            {
                Turn_Off_LED();
            }


            // =================================
            // ??
            //
            // A?
            // B?
            //
            // ??:
            // 20 / 150
            //
            // ???:
            // -20 / -150
            //
            // ???????
            // =================================

            else if (
                CAR_buff[1]
                <
                CAR_buff[3]
            )
            {
                Turn_Left_LED();
            }


            // =================================
            // ??
            //
            // A?
            // B?
            //
            // ??:
            // 150 / 20
            // =================================

            else if (
                CAR_buff[1]
                >
                CAR_buff[3]
            )
            {
                Turn_Right_LED();
            }


            // =================================
            // ????
            // =================================

            else
            {
                Turn_Off_LED();
            }


            uart_rec_flag = 0;
        }


        delay_ms(5);
    }
}